// footer_operator_images 가 현재 스키마(스쿼시한 baseline 이후 마이그레이션 전체)에 테이블, RLS,
// QA 쓰기 차단 트리거를 담는지 잠근다. 원격 DB 에는 적용하지 않으므로 SQL 텍스트로만 본다.
// 데이터 문장은 마이그레이션에 두지 않는다.
// pg_dump 형식이라 컬럼은 CREATE TABLE 본문에, 제약과 인덱스와 정책은 별도 문장에 있다.

import { expect, test } from "vitest";
import { MIGRATIONS_SQL } from "../../../../supabase/grants/migrationGrants";

function flatSql(): string {
  return MIGRATIONS_SQL.replace(/\s+/g, " ");
}

function tableBody(table: string): string {
  const match = MIGRATIONS_SQL.match(
    new RegExp(
      `CREATE TABLE IF NOT EXISTS "public"\\."${table}" \\(([\\s\\S]*?)\\n\\);`,
    ),
  );
  expect(match).not.toBeNull();
  return (match as RegExpMatchArray)[1] ?? "";
}

test("제목, 이미지 주소, 순서, 노출 여부를 가진 footer_operator_images 테이블이 있다", () => {
  const body = tableBody("footer_operator_images");
  expect(body).toMatch(/^\s+"id" bigint NOT NULL,$/m);
  // 관리자 수정 저장이 id 를 그대로 되돌려 보내므로 always 가 아니라 by default 여야 한다.
  const sql = flatSql();
  expect(sql).toContain(
    'ALTER TABLE "public"."footer_operator_images" ALTER COLUMN "id" ADD GENERATED BY DEFAULT AS IDENTITY (',
  );
  expect(sql).toContain(
    'ALTER TABLE ONLY "public"."footer_operator_images" ADD CONSTRAINT "footer_operator_images_pkey" PRIMARY KEY ("id");',
  );
  expect(body).toMatch(/^\s+"title" "text" NOT NULL,$/m);
  expect(body).toMatch(/^\s+"image_url" "text" NOT NULL,$/m);
  expect(body).toMatch(/^\s+"sort_order" integer DEFAULT 0 NOT NULL,$/m);
  expect(body).toMatch(/^\s+"is_active" boolean DEFAULT true NOT NULL,$/m);
  expect(body).toMatch(
    /^\s+"created_at" timestamp with time zone DEFAULT "now"\(\) NOT NULL,$/m,
  );
  expect(body).toMatch(
    /^\s+"updated_at" timestamp with time zone DEFAULT "now"\(\) NOT NULL,$/m,
  );
  expect(sql).toContain(
    'BEFORE UPDATE ON "public"."footer_operator_images" FOR EACH ROW EXECUTE FUNCTION "public"."set_updated_at"();',
  );
});

test("RLS 가 켜져 있고 공개는 노출 행만 읽고 쓰기는 관리자만 한다", () => {
  const sql = flatSql();
  expect(sql).toContain(
    'ALTER TABLE "public"."footer_operator_images" ENABLE ROW LEVEL SECURITY;',
  );
  expect(sql).toContain(
    'CREATE POLICY "footer_operator_images public read" ON "public"."footer_operator_images" FOR SELECT TO "authenticated", "anon" USING ("is_active");',
  );
  expect(sql).toContain(
    'CREATE POLICY "footer_operator_images admin all" ON "public"."footer_operator_images" TO "authenticated" USING ("public"."is_winning_admin"()) WITH CHECK ("public"."is_winning_admin"());',
  );
  for (const role of ["anon", "authenticated", "service_role"]) {
    expect(sql).toContain(
      `GRANT ALL ON TABLE "public"."footer_operator_images" TO "${role}";`,
    );
  }
});

test("QA 본사 관리자 쓰기 차단 문 단위 트리거를 한 줄로 건다", () => {
  expect(MIGRATIONS_SQL).toContain(
    'CREATE OR REPLACE TRIGGER "trg_qa_admin_write_block" BEFORE INSERT OR DELETE OR UPDATE ON "public"."footer_operator_images" FOR EACH STATEMENT EXECUTE FUNCTION "public"."fn_block_qa_admin_write"();',
  );
});

test("마이그레이션에는 데이터 문장을 두지 않는다", () => {
  // 함수 본문은 들여쓰기가 있으므로 줄 맨 앞의 데이터 문장만 본다.
  expect(MIGRATIONS_SQL).not.toMatch(
    /^(insert\s+into|update\s|delete\s+from)/im,
  );
});

test("노출 대상 tenant_id 가 tenants 를 참조하고 null 허용이며 인덱스와 설명이 있다", () => {
  const sql = flatSql();
  // NOT NULL 이 붙으면 마지막 컬럼 줄이 `"uuid" NOT NULL` 이 되어 맞지 않는다.
  expect(tableBody("footer_operator_images")).toMatch(
    /^\s+"tenant_id" "uuid"$/m,
  );
  expect(sql).toContain(
    'ALTER TABLE ONLY "public"."footer_operator_images" ADD CONSTRAINT "footer_operator_images_tenant_id_fkey" FOREIGN KEY ("tenant_id") REFERENCES "public"."tenants"("id");',
  );
  expect(sql).toContain(
    'CREATE INDEX "footer_operator_images_tenant_id_idx" ON "public"."footer_operator_images" USING "btree" ("tenant_id");',
  );
  expect(sql).toMatch(
    /COMMENT ON COLUMN "public"\."footer_operator_images"\."tenant_id" IS '[^']*공통[^']*';/,
  );
  expect(sql).toMatch(
    /COMMENT ON TABLE "public"\."footer_operator_images" IS /,
  );
});
