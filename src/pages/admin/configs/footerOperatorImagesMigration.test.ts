// footer_operator_images 마이그레이션이 테이블, RLS, QA 쓰기 차단 트리거를 담는지 잠근다.
// 원격 DB 에는 적용하지 않으므로 파일 내용으로만 본다. 데이터 문장은 마이그레이션에 두지 않는다.

import fs from "node:fs";
import path from "node:path";
import { expect, test } from "vitest";

const MIGRATIONS = path.resolve(
  import.meta.dirname,
  "../../../../supabase/migrations",
);

function readMigration(): string {
  const file = fs
    .readdirSync(MIGRATIONS)
    .find((name) => name.endsWith("_footer_operator_images.sql"));
  expect(file).toBeDefined();
  return fs.readFileSync(path.join(MIGRATIONS, file as string), "utf8");
}

test("제목, 이미지 주소, 순서, 노출 여부를 가진 footer_operator_images 테이블을 만든다", () => {
  const sql = readMigration();
  expect(sql).toMatch(
    /create table if not exists public\.footer_operator_images/i,
  );
  // 관리자 수정 저장이 id 를 그대로 되돌려 보내므로 always 가 아니라 by default 여야 한다.
  expect(sql).toMatch(
    /id bigint generated by default as identity primary key/i,
  );
  expect(sql).toMatch(/title text not null/i);
  expect(sql).toMatch(/image_url text not null/i);
  expect(sql).toMatch(/sort_order integer not null default 0/i);
  expect(sql).toMatch(/is_active boolean not null default true/i);
  expect(sql).toMatch(/created_at timestamptz not null default now\(\)/i);
  expect(sql).toMatch(/updated_at timestamptz not null default now\(\)/i);
  expect(sql).toMatch(
    /before update on public\.footer_operator_images\s+for each row execute function public\.set_updated_at\(\)/i,
  );
});

test("RLS 를 켜고 공개는 노출 행만 읽고 쓰기는 관리자만 한다", () => {
  const sql = readMigration();
  expect(sql).toMatch(
    /alter table public\.footer_operator_images enable row level security/i,
  );
  expect(sql).toMatch(
    /for select to authenticated, anon\s+using \(is_active\)/i,
  );
  expect(sql).toMatch(
    /to authenticated\s+using \(public\.is_winning_admin\(\)\)\s+with check \(public\.is_winning_admin\(\)\)/i,
  );
  expect(sql).toMatch(
    /grant all on table public\.footer_operator_images to anon, authenticated, service_role;/i,
  );
});

test("QA 본사 관리자 쓰기 차단 문 단위 트리거를 한 줄로 건다", () => {
  expect(readMigration()).toContain(
    "create trigger trg_qa_admin_write_block before insert or update or delete on public.footer_operator_images for each statement execute function public.fn_block_qa_admin_write();",
  );
});

test("마이그레이션에는 데이터 문장을 두지 않는다", () => {
  expect(readMigration()).not.toMatch(
    /\b(insert\s+into|update\s+public\.\w+\s+set|delete\s+from)\b/i,
  );
});
