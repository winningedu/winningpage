-- 푸터 왼쪽에 보이는 운영기관 이미지를 관리자에서 올리고 고른다. 사이트별 DB 가 분리돼 있어 사이트 컬럼은 없다.
-- 스키마만 담는다. 메뉴 행은 supabase/data/ 의 admin_resources_footer_images.sql 로 수동 실행한다.

create table if not exists public.footer_operator_images (
  id bigint generated by default as identity primary key,
  title text not null,
  image_url text not null,
  sort_order integer not null default 0,
  is_active boolean not null default true,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

comment on table public.footer_operator_images is '푸터 운영기관 이미지. 공개 화면은 is_active 행 중 sort_order, id 순 첫 행 하나만 그린다. 행이 없으면 이미지 자리를 그리지 않는다.';
comment on column public.footer_operator_images.title is '관리자 목록 이름이자 img alt.';
comment on column public.footer_operator_images.image_url is 'banners 버킷 공개 URL.';

create trigger trg_footer_operator_images_updated_at
  before update on public.footer_operator_images
  for each row execute function public.set_updated_at();

alter table public.footer_operator_images enable row level security;

create policy "footer_operator_images public read" on public.footer_operator_images
  for select to authenticated, anon using (is_active);

create policy "footer_operator_images admin all" on public.footer_operator_images
  to authenticated
  using (public.is_winning_admin())
  with check (public.is_winning_admin());

grant all on table public.footer_operator_images to anon, authenticated, service_role;

create trigger trg_qa_admin_write_block before insert or update or delete on public.footer_operator_images for each statement execute function public.fn_block_qa_admin_write();
